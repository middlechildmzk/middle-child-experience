create unique index if not exists bvss_search_metrics_unique on public.bvss_search_metrics(
  metric_date,
  coalesce(playlist_id,'00000000-0000-0000-0000-000000000000'::uuid),
  page_path,
  coalesce(query,''),
  source
);

create table if not exists public.bvss_submissions (
  id uuid primary key default gen_random_uuid(),
  artist_name text not null check (char_length(trim(artist_name)) between 1 and 160),
  email text not null check (position('@' in email) > 1),
  song_title text not null check (char_length(trim(song_title)) between 1 and 200),
  spotify_url text not null,
  spotify_track_id text,
  release_date date,
  genre text not null check (char_length(trim(genre)) between 1 and 120),
  moods text[] not null default '{}',
  comparable_artists text[] not null default '{}',
  is_explicit boolean not null default false,
  notes text check (notes is null or char_length(notes) <= 4000),
  preferred_playlist_ids uuid[] not null default '{}',
  status text not null default 'pending' check (status in ('pending','in_review','hold','accepted','rejected','withdrawn')),
  submission_source text not null default 'bvssfvm.com',
  duplicate_fingerprint text generated always as (
    md5(lower(trim(email)) || '|' || coalesce(spotify_track_id, lower(trim(spotify_url))))
  ) stored,
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (duplicate_fingerprint)
);
create index if not exists bvss_submissions_status_time_idx on public.bvss_submissions(status,submitted_at desc);

