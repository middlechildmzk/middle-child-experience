create table if not exists public.bvss_search_metrics (
  id bigint generated by default as identity primary key,
  metric_date date not null,
  playlist_id uuid references public.bvss_playlists(id) on delete cascade,
  page_path text not null,
  query text,
  clicks integer not null default 0 check (clicks >= 0),
  impressions integer not null default 0 check (impressions >= 0),
  ctr numeric(8,6) check (ctr is null or (ctr >= 0 and ctr <= 1)),
  position numeric(8,3) check (position is null or position >= 0),
