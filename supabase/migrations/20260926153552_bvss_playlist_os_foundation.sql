create table if not exists public.bvss_playlists (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  spotify_playlist_id text not null unique,
  spotify_uri text not null unique,
  spotify_url text not null,
  canonical_name text not null,
  subtitle text not null default '',
  description text not null default '',
  cover_asset_url text,
  primary_genre text not null,
  secondary_genres text[] not null default '{}',
  moods text[] not null default '{}',
  activities text[] not null default '{}',
  seo_keywords text[] not null default '{}',
  anchor_artists text[] not null default '{}',
  target_track_count integer not null default 70 check (target_track_count between 10 and 500),
  current_track_count integer check (current_track_count is null or current_track_count >= 0),
  current_follower_count bigint check (current_follower_count is null or current_follower_count >= 0),
  follower_count_source text,
  follower_count_observed_at timestamptz,
  spotify_created_date date,
  spotify_last_synced_at timestamptz,
  last_editorial_update_at timestamptz,
  public_status text not null default 'public' check (public_status in ('draft','public','private')),
  submission_status text not null default 'open' check (submission_status in ('open','paused','closed')),
  update_cadence text not null default 'weekly',
  middle_child_eligible boolean not null default true,
  subflower_eligible boolean not null default false,
  website_status text not null default 'published' check (website_status in ('draft','published','hidden')),
  lifecycle_state text not null default 'active' check (lifecycle_state in ('active','experimental','archived')),
  curation_philosophy text not null default '',
  submission_criteria text not null default '',
  display_order integer not null default 100,
  source_metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(source_metadata)='object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bvss_playlist_metric_snapshots (
  id uuid primary key default gen_random_uuid(),
  playlist_id uuid not null references public.bvss_playlists(id) on delete cascade,
  metric_date date not null,
  followers bigint check (followers is null or followers >= 0),
  track_count integer check (track_count is null or track_count >= 0),
  source text not null,
  source_ref text,
  raw_data jsonb not null default '{}'::jsonb,
  observed_at timestamptz not null default now(),
  unique (playlist_id, metric_date, source)
);
create index if not exists bvss_playlist_metric_playlist_date_idx on public.bvss_playlist_metric_snapshots(playlist_id,metric_date desc);

create table if not exists public.bvss_playlist_tracks (
